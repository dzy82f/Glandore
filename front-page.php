		<h2 id="login-modal-title" class="login-modal-heading">Member login</h2>
		<div class="login-modal-form">
			<?php echo do_shortcode( '[user_registration_login]' ); ?>
		</div>
	</div>
</div>

<?php get_template_part( 'template_parts/modals/modal-registration' ); ?>

<?php get_footer(); ?>