    <h3>Privacy</h3>

    <p>
        Glandore respects your privacy. This site publishes research-led materials
        and offers participation in activities associated with the Tychevia framework
        to registered users.
    </p>

    <h4>Registration and participation</h4>

    <p>
        Participation is offered to users who register with a valid email address.
        Additional information, such as region, professional role, seniority or areas
        of interest, is optional and may be provided at your discretion.
    </p>

    <h4>What information we collect</h4>

    <p>
        We collect email addresses for the purpose of account management and
        communication related to participation. Where provided voluntarily, we may
        also collect additional profile information to better understand interests
        and engagement.
    </p>

    <p>
        We also process limited technical information (for example IP address,
        browser type and pages accessed) to operate the site, maintain security
        and understand aggregate usage.
    </p>

    <h4>How information is used</h4>

    <p>
        Information is used to operate the platform, manage participation,
        improve published materials and support research and learning activities.
        We do not sell personal data.
    </p>

    <h4>Legal basis</h4>

    <p>
        Processing of registration and profile information is based on consent.
        Some technical processing is carried out on the basis of legitimate interests
        in operating, securing and improving the site.
    </p>

    <h4>Your rights</h4>

    <p>
        You may request access to, correction or deletion of your information, and
        you may withdraw consent where consent is the basis for processing.
        To do so, contact <a href="mailto:privacy@glandore.com">privacy@glandore.com</a>.
    </p>

