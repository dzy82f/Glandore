    <h3>Communities of Practice</h3>
	
<p>
  Between 1994 and 2004
  <a href="https://www.linkedin.com/in/richard-karash-653335/" target="_blank" rel="noopener noreferrer">Richard Karash</a>
  created the Learning-Org Internet Dialogue on Organizational Learning, an early example of a
  <a href="https://staging.glandore.com/wp-content/uploads/2020/05/Communities-of-Practice_-The-Organizational-Frontier.pdf" target="_blank" rel="noopener noreferrer">Community of Practice</a>
  or CoP. I derived a great deal of pleasure from participating in the Dialogue which taught me a great deal and had a profound influence on my thinking about “systems” and the way organisations operate ever since.
</p>

<p>
  A CoP is a group of people who share a concern, craft or passion and who deepen their knowledge and skill by interacting regularly. It isn’t just a team or a network; it’s held together by three things: a shared domain, community and practice. Over time, a community of practice becomes the place where that practice “lives” and evolves.
</p>

<p>
  This is an experiment to build on Rich’s seminal work and to create a CoP taking advantage of the advances in software development and the use of LLMs such as ChatGPT that have taken place since 2004. In particular in its use of Agentic AI principles to moderate contributions.
</p>

<p>It is the inverse of what might be done in LinkedIn, WhatsApp or Facebook by:</p>

<ul>
  <li>Being designed as a thinking environment – a slow, branching conversation that can learn over time.</li>
  <li>Having a centre of gravity based on topics and shared inquiry based on topic canopies, threads and branches.</li>
  <li>Recognising that whilst the social graph matters, contributors matter more.</li>
</ul>

<p>Thus, in summary:</p>

<ul>
  <li>LinkedIn, WhatsApp, and Facebook are excellent at connecting people and generating activity.</li>
  <li>The CoP is being designed to be excellent at holding questions and accumulating understanding.</li>
</ul>

<p>They are not competitors so much as different instruments.</p>

