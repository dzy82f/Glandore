	<h4>Site build</h4>
	
	<p style="text-align:center">
    <strong>Plan to throw one away — you will anyway.</strong><br>
    Fred Brooks, <em>The Mythical Man-Month</em>.
	</p>
	 
	
	<p>Two approaches were thrown away in the devlopment of this site. <em>Astra</em> was found to be too opinionated with too many abstractions and defaults to fight. It seemed to be optimised for page builders, not architectural clarity. <em>GeneratePress</em> appeared to be cleaner than Astra, but was still a framework rather than a scaffold. Too much of the “theme logic” was baked in and it seemed the developer had to adapt to the theme's structure, rather than the other way round. 
	</p>
	
	<p>
	Thus, <em>glandore.com</em> was built from the ground up in deliberate opposition to the constraints imposed by so-called <em>code-free</em> site builders and heavily opinionated WordPress themes. Such tools often invert the proper relationship between developer and system, forcing the developer to adapt their thinking to the abstractions, conventions, and limitations embedded in the theme, rather than allowing the site architecture to arise from first principles.
	</p>

	<p>
	To avoid this inversion, the site was implemented using the <em>_s</em> (Underscores) scaffold as a minimal structural base rather than a prescriptive theme framework. WordPress was treated strictly as a rendering and content-management layer. "Off-the-shelf" plugins where possible. Pages are composed primarily from bespoke <code>.php</code> templates, <code>.css</code> and the carefully constrained use of <code>.js</code> only where interaction genuinely requires it. This keeps behaviour explicit, traceable, and resistant to unintended coupling introduced by theme-level automation.
	</p>

	<p>
	The development process itself mirrored this architectural philosophy. Rather than following a fixed specification or pre-defined component library, the site emerged through an interactive dialogue between a human designer and a digital Associate within the Tychevia framework. The human articulated intentions around layout, interaction, rhythm, and constraint; these were then examined, challenged, and refined through dialogue before being translated by the agent into concrete templates and scripts. In this way, both the structure of the site and the method of its creation prioritised intentionality, clarity, and mutual adjustment over convenience or automation.
	</p>