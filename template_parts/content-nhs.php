<h3>NHS</h3>

<p>
At a system level, the NHS presents a distinctly wicked problem. Demand is
unbounded, resources are finite, and moral obligation is absolute. There is no
stable definition of success against which the system can be optimised.
</p>

<p>
Tychevia is used in NHS contexts not to design solutions, but to enable honest
thinking in conditions where certainty is unavailable and reform fatigue is
structural.
</p>

<h4>The NHS question</h4>

<p>
NHS work begins with a different kind of question:
</p>

<p><em>
How can a health system remain coherent, credible, and learnable when it is
under permanent pressure and subject to continuous reform?
</em></p>

<p>
This shifts the focus away from isolated failures and toward recurring patterns
of overload, governance fragility, and institutional amnesia.
</p>

<h4>Desk research and institutional memory</h4>

<p>
Desk research in the NHS is extensive but selective. National reviews, service
plans, workforce data, and past reform initiatives are examined primarily to
understand what has already been tried — and what has been forgotten.
</p>

<p>
This material is assembled into a Knowledge Engine that explicitly incorporates
history, governance structures, and competing narratives. The aim is not to
resolve disagreement, but to make it visible and traceable.
</p>

<h4>Sense-making in a wicked system</h4>

<p>
Sense-making in the NHS places particular weight on governance and power,
incentives, and lived experience. Causal Loop Diagrams are used to surface
reinforcing dynamics such as demand growth, workforce attrition, and short-term
political cycles.
</p>

<p>
Root convergence focuses on why the same issues reappear despite repeated
intervention. Where tensions cannot be resolved through analysis alone,
dialectical reasoning is used to reframe the problem space rather than force
trade-offs.
</p>

<h4>Learning rather than reform</h4>

<p>
Interventions are approached cautiously. The emphasis is on preserving learning,
protecting institutional memory, and avoiding reforms that satisfy narrative
pressure while degrading long-term coherence.
</p>

<p>
In the NHS, Tychevia’s distinctive contribution lies in making thinking durable
in a system that is otherwise designed to forget.
</p>

<h4>NHS proposals</h4>

<p>
In the NHS, proposals serve a different purpose. Because the system operates
under permanent pressure and moral obligation, Tychevia proposals are designed
to protect coherence rather than promise resolution.
</p>

<p>
NHS proposals typically focus on:
</p>

<ul>
    <li>stabilising governance and decision rights</li>
    <li>making trade-offs explicit rather than implicit</li>
    <li>preserving institutional memory across reform cycles</li>
    <li>identifying actions that reduce systemic brittleness</li>
</ul>

<p>
Rather than offering “solutions”, proposals function as holding structures:
they define what should not be lost, what must be protected, and where cautious
intervention is possible without degrading trust or safety.
</p>

<p>
In this sense, NHS proposals are less about change programmes and more about
stewardship under enduring uncertainty.
</p>

