<h3>Method</h3>

<p>
Tychevia is not a method in the conventional sense. It is a disciplined way of
thinking and acting when the problem itself is unstable, contested, or only
partly knowable. In such conditions, applying techniques in isolation is not
just ineffective — it is actively misleading.
</p>

<p>
The purpose of the Tychevia method is therefore not to “apply tools”, but to
maintain coherence of judgement as understanding evolves. Methods are used only
when the nature of the problem makes them necessary, and always in relation to
what has come before.
</p>

<h4>The underlying question</h4>

<p>
At the heart of Tychevia is a single epistemic question:
</p>

<p><em>
How do we think and act well when the problem cannot be fully specified in
advance, and certainty is neither available nor honest?
</em></p>

<p>
Every element of the method exists to answer that question. The sequence matters.
Without it, even sophisticated techniques collapse into premature solutions or
false confidence.
</p>

<h4>The thinking sequence</h4>

<p>
The Tychevia method unfolds as a sequence of inquiry. Each stage prepares the
conditions for the next.
</p>

<p>
<strong>Orientation.</strong> First, we establish what kind of problem we are in.
This includes boundary setting and distinguishing between tame, complicated,
complex, and wicked situations. The aim is to prevent category error before any
analysis begins.
</p>

<p>
<strong>Sense-making.</strong> Next, the problem is examined through a small number
of deliberately contrasting lenses. The issue is held constant while the
interpretive frame changes, allowing blind spots, tensions, and structural
features to become visible without pretending to resolve them.
</p>

<p>
<strong>Root convergence.</strong> Where patterns recur, drilling methods are used
to distinguish symptoms from systemic drivers. This stage focuses on why issues
reappear across time, domains, or reforms, rather than why they occur once.
</p>

<p>
<strong>Intervention design.</strong> Only then are intervention pathways explored.
The emphasis is on leverage, constraints, and safe-to-fail action rather than
control or optimisation. Action is treated as provisional and revisable.
</p>

<p>
<strong>Narrative, learning, and memory.</strong> Finally, what has been learned is
made durable. Narratives, artefacts, and decision traces are created so that
understanding survives personnel change, political cycles, and regime shifts.
</p>

<h4>What this approach avoids</h4>

<p>
Tychevia is not a toolkit, a prompt library, or an optimisation engine. It does
not promise certainty, speed, or universal solutions. Methods are not explained
or applied in isolation, and no single lens or diagnostic is privileged.
</p>

<p>
Instead, methods are introduced only at the point in the thinking where they
become unavoidable.
</p>

<p><em>
Tychevia does not choose methods in advance; it allows the nature of the problem
to summon the methods it requires.
</em></p>

<h4>Why this scales</h4>

<p>
This is why the same method coheres across public services, corporates, and
financial institutions. The surface problems differ, but the underlying
challenge is the same: maintaining coherent judgement under conditions where
easy answers are rewarded and good thinking is not.
</p>

