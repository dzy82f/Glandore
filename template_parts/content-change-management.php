<h3>Managing Change</h3>

<p>Organisations are rarely short of ideas about how to change. New strategies are introduced, structures are revised, and individuals are asked to adapt. Yet despite this activity, outcomes often disappoint.</p>

<p>When this happens, the explanation typically settles on people. Individuals are described as resistant, underperforming, or lacking capability. The assumption is that if behaviour is not as expected, the cause must lie with the person.</p>

<p>This explanation is appealing because it is simple and visible. People can be identified. Systems cannot. As a result, the individual becomes the focal point for diagnosis and intervention.</p>

<p>However, behaviour does not arise in isolation. It is shaped by roles, processes, incentives, constraints, and the often conflicting demands placed upon individuals within organisations. What appears to be a personal shortcoming is frequently a rational response to conditions that are poorly understood.</p>

<p>This creates a recurring pattern. Problems generated by systems are interpreted as failures of individuals. Interventions are then directed at the person rather than the conditions that produced the behaviour. In such cases, change efforts may be well-intentioned but misdirected.</p>

<p>The four papers presented here explore this challenge from different perspectives. The first examines why organisations misdiagnose people. The second offers a structured approach to understanding behaviour in context. The third considers how established change methods depend on the correctness of the direction in which they are applied. The fourth introduces the Tychevia Process as a structured approach to inquiry in conditions of uncertainty, contestation, and systemic instability.</p>

<p>Together, these papers argue for a simple but important shift. More effective change begins not with correcting individuals, but with understanding the conditions that shape what they do. In this view, method is not a means of control or optimisation, but a way of maintaining coherent judgement where certainty is unavailable and action must proceed without illusion.</p>

