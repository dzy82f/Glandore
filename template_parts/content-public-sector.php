<h3>Public sector</h3>

<p>
Public sector work typically begins with problems that are politically visible,
socially contested, and structurally entangled across multiple institutions.
While some elements may be technically solvable, many of the most persistent
issues resist clear ownership or stable problem definition.
</p>

<p>
Tychevia is used in public sector contexts to restore clarity of thinking before
solutions are proposed. The emphasis is not on optimisation or delivery, but on
establishing what kind of problem is actually being faced and where meaningful
agency exists.
</p>

<h4>Framing the question</h4>

<p>
Public sector questions are often posed in the language of policy or performance.
Tychevia reframes these into epistemic questions, such as:
</p>

<ul>
    <li>What problem is this system repeatedly failing to resolve?</li>
    <li>Where is responsibility formally assigned but practically constrained?</li>
    <li>Which tensions are structural rather than contingent?</li>
</ul>

<p>
This reframing prevents premature convergence on reforms that address symptoms
rather than causes.
</p>

<h4>Desk research and the knowledge engine</h4>

<p>
Desk research is used proportionately and purposefully. Existing reports, policy
documents, performance data, and prior reform narratives are reviewed not to
accumulate evidence, but to surface assumptions, points of disagreement, and
institutional memory loss.
</p>

<p>
This material feeds into a Knowledge Engine — a defined Domain of Interest that
brings together relevant sources, perspectives, and analytical frames. The aim
is to create an epistemic container within which sense-making can occur, rather
than to exhaustively model the system.
</p>

<h4>Sense-making under constraint</h4>

<p>
Sense-making focuses on governance, incentives, culture, and lived experience.
Causal structures are explored to understand why problems persist across policy
cycles and organisational change. Interventions are treated as provisional and
constrained by democratic accountability and public trust.
</p>

<p>
Across public services, Tychevia is used to strengthen how institutions think
about complexity, uncertainty, and contested narratives — so that action remains
coherent even when consensus does not.
</p>

<h4>From sense-making to proposals</h4>

<p>
In public sector contexts, Tychevia proposals are designed to be decision-relevant
rather than prescriptive. They do not take the form of implementation plans or
policy blueprints.
</p>

<p>
Instead, proposals articulate:
</p>

<ul>
    <li>clear problem framings that can be held consistently over time</li>
    <li>identified leverage points and constraints within existing governance</li>
    <li>options for action that are proportionate, testable, and politically honest</li>
</ul>

<p>
Proposals are framed to support judgement by ministers, officials, and system
leaders, rather than to substitute for it. They are explicitly designed to travel
across departments and electoral cycles without collapsing into slogans.
</p>

